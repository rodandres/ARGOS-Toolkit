import os
import numpy as np
import matplotlib.pyplot as plt


# ==============================================================================
# CONFIGURATION
# ==============================================================================

chaser_name = "Chaser"
target_name = "Target"

HISTORY_DIRECTORY = "simulation_history"

TIME_FACTOR_SEC = 27.321661 / (2.0 * np.pi) * 24 * 3600     # time unit unidad -> sideral lunar month (days)

SIM_MAX_TIME = 0.75952417*2 * TIME_FACTOR_SEC #60*13

ORBIT_MAX_TIME = SIM_MAX_TIME
RELATIVE_MAX_TIME = 60 * 12


# ==============================================================================
# LOAD HISTORY FROM CSV
# ==============================================================================

def load_spacecraft_history(
    spacecraft_name,
    directory,
):
    """
    Loads the time and true position history of a spacecraft
    from the CSV files generated by save_simulation_history_csv().
    """

    spacecraft_directory = os.path.join(
        directory,
        spacecraft_name,
    )

    t_path = os.path.join(
        spacecraft_directory,
        "t.csv",
    )

    position_path = os.path.join(
        spacecraft_directory,
        "true_state_position.csv",
    )

    if not os.path.isfile(t_path):
        raise FileNotFoundError(
            f"Time history not found:\n{t_path}"
        )

    if not os.path.isfile(position_path):
        raise FileNotFoundError(
            f"Position history not found:\n{position_path}"
        )

    # --------------------------------------------------------------------------
    # Time
    # --------------------------------------------------------------------------

    t = np.loadtxt(
        t_path,
        delimiter=",",
        skiprows=1,
    )

    # --------------------------------------------------------------------------
    # Position
    # --------------------------------------------------------------------------

    position = np.loadtxt(
        position_path,
        delimiter=",",
    )

    position = np.atleast_2d(position)

    if position.shape[1] != 3:
        raise ValueError(
            f"{spacecraft_name}: position must have shape (N, 3), "
            f"but got {position.shape}."
        )

    return t, position


# ==============================================================================
# LOAD CHASER AND TARGET
# ==============================================================================

chaser_t, chaser_position = load_spacecraft_history(
    chaser_name,
    HISTORY_DIRECTORY,
)

target_t, target_position = load_spacecraft_history(
    target_name,
    HISTORY_DIRECTORY,
)


# ==============================================================================
# VALIDATE DATA
# ==============================================================================

if len(chaser_t) != len(chaser_position):

    raise ValueError(
        f"{chaser_name}: time and position have different lengths: "
        f"{len(chaser_t)} vs {len(chaser_position)}"
    )


if len(target_t) != len(target_position):

    raise ValueError(
        f"{target_name}: time and position have different lengths: "
        f"{len(target_t)} vs {len(target_position)}"
    )


# ==============================================================================
# SORT BY TIME
# ==============================================================================

chaser_indices = np.argsort(chaser_t)

chaser_t = chaser_t[chaser_indices]
chaser_position = chaser_position[chaser_indices]


target_indices = np.argsort(target_t)

target_t = target_t[target_indices]
target_position = target_position[target_indices]


# ==============================================================================
# COMMON TIME FOR COMPLETE ORBIT
# ==============================================================================

orbit_t_min = max(
    chaser_t[0],
    target_t[0],
)

orbit_t_max = min(
    chaser_t[-1],
    target_t[-1],
    ORBIT_MAX_TIME,
)

if orbit_t_max <= orbit_t_min:

    raise ValueError(
        "No common time interval exists for the complete orbit."
    )


chaser_orbit_t = chaser_t[
    (chaser_t >= orbit_t_min)
    &
    (chaser_t <= orbit_t_max)
]

target_orbit_t = target_t[
    (target_t >= orbit_t_min)
    &
    (target_t <= orbit_t_max)
]


orbit_t = np.unique(
    np.concatenate(
        [
            chaser_orbit_t,
            target_orbit_t,
        ]
    )
)


# ==============================================================================
# INTERPOLATE COMPLETE ORBIT
# ==============================================================================

chaser_orbit_position = np.column_stack(
    [
        np.interp(
            orbit_t,
            chaser_t,
            chaser_position[:, i],
        )
        for i in range(3)
    ]
)


target_orbit_position = np.column_stack(
    [
        np.interp(
            orbit_t,
            target_t,
            target_position[:, i],
        )
        for i in range(3)
    ]
)


# ==============================================================================
# COMMON TIME FOR RELATIVE MOTION
# ==============================================================================

relative_t_min = max(
    chaser_t[0],
    target_t[0],
)

relative_t_max = min(
    chaser_t[-1],
    target_t[-1],
    RELATIVE_MAX_TIME,
)

if relative_t_max <= relative_t_min:

    raise ValueError(
        "No common time interval exists for the relative motion."
    )


chaser_relative_t = chaser_t[
    (chaser_t >= relative_t_min)
    &
    (chaser_t <= relative_t_max)
]

target_relative_t = target_t[
    (target_t >= relative_t_min)
    &
    (target_t <= relative_t_max)
]


relative_t = np.unique(
    np.concatenate(
        [
            chaser_relative_t,
            target_relative_t,
        ]
    )
)


# ==============================================================================
# INTERPOLATE RELATIVE MOTION
# ==============================================================================

chaser_relative_position = np.column_stack(
    [
        np.interp(
            relative_t,
            chaser_t,
            chaser_position[:, i],
        )
        for i in range(3)
    ]
)


target_relative_position = np.column_stack(
    [
        np.interp(
            relative_t,
            target_t,
            target_position[:, i],
        )
        for i in range(3)
    ]
)


# ==============================================================================
# RELATIVE POSITION
#
# r_C/T = r_C - r_T
# ==============================================================================

relative_position = (
    chaser_relative_position
    - target_relative_position
)


# ==============================================================================
# FIGURE
# ==============================================================================

fig = plt.figure(
    figsize=(18, 6),
)


# ==============================================================================
