# EQUAL ASPECT RATIO FOR 3D PLOTS
# ==============================================================================

def set_equal_3d_axes(ax, data):

    x = data[:, 0]
    y = data[:, 1]
    z = data[:, 2]

    x_range = np.ptp(x)
    y_range = np.ptp(y)
    z_range = np.ptp(z)

    max_range = max(
        x_range,
        y_range,
        z_range,
    )

    if max_range == 0:
        max_range = 1.0

    x_mid = (
        x.max()
        + x.min()
    ) / 2

    y_mid = (
        y.max()
        + y.min()
    ) / 2

    z_mid = (
        z.max()
        + z.min()
    ) / 2

    ax.set_xlim(
        x_mid - max_range / 2,
        x_mid + max_range / 2,
    )

    ax.set_ylim(
        y_mid - max_range / 2,
        y_mid + max_range / 2,
    )

    ax.set_zlim(
        z_mid - max_range / 2,
        z_mid + max_range / 2,
    )


set_equal_3d_axes(
    ax1,
    np.vstack(
        [
            chaser_orbit_position,
            target_orbit_position,
        ]
    ),
)


